/**
 * Central translation lookup function `translate(lang, key, params)`
 * Interpolates `{param}` placeholders and formats numbers in the active locale.
 */
export function translate(
  lang: LanguageCode,
  key: TranslationKey,
  params?: Record<string, string | number>
): string {
  const dict = TRANSLATIONS[lang];
  let template = dict[key];
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      const formattedVal = typeof v === 'number' ? formatNumber(v, lang) : String(v);
      template = template.replace(new RegExp(`\\{${k}\\}`, 'g'), formattedVal);
    }
  }
  return template;
}
