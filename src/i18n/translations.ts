export function isRtlLanguage(lang: LanguageCode): boolean {
  return lang === 'ar' || lang === 'ur';
}

const BENGALI_DIGITS = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];
const DEVANAGARI_DIGITS = ['०', '१', '२', '३', '४', '५', '६', '७', '८', '९'];
const ARABIC_DIGITS = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];
const URDU_DIGITS = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹'];

export function formatNumber(val: number | string, lang: LanguageCode): string {
  const str = String(val);
  if (lang === 'bn') {
    return str.replace(/[0-9]/g, (d) => BENGALI_DIGITS[Number(d)]);
  }
  if (lang === 'hi' || lang === 'ne') {
    return str.replace(/[0-9]/g, (d) => DEVANAGARI_DIGITS[Number(d)]);
  }
  if (lang === 'ar') {
    return str.replace(/[0-9]/g, (d) => ARABIC_DIGITS[Number(d)]);
  }
  if (lang === 'ur') {
    return str.replace(/[0-9]/g, (d) => URDU_DIGITS[Number(d)]);
  }
  return str;
}

const BENGALI_ROW_NAMES = ['১ম', '২য়', '৩য়', '৪র্থ', '৫ম', '৬ষ্ঠ', '৭ম', '৮ম', '৯ম'];
const BENGALI_COL_NAMES = ['ক', 'খ', 'গ', 'ঘ', 'ঙ'];
const DEVANAGARI_COL_NAMES = ['क', 'ख', 'ग', 'घ', 'ङ'];
const ARABIC_COL_NAMES = ['أ', 'ب', 'ج', 'د', 'هـ'];
const URDU_COL_NAMES = ['ا', 'ب', 'ج', 'د', 'ہ'];
const LATIN_COL_NAMES = ['A', 'B', 'C', 'D', 'E'];

export function formatBoardCoord(row: number, col: number, lang: LanguageCode): string {
  const safeRow = Math.max(0, Math.min(8, row));
  const safeCol = Math.max(0, Math.min(4, col));
  if (lang === 'bn') {
    return `${BENGALI_ROW_NAMES[safeRow]}-${BENGALI_COL_NAMES[safeCol]}`;
  }
  if (lang === 'hi' || lang === 'ne') {
    return `${formatNumber(safeRow + 1, lang)}-${DEVANAGARI_COL_NAMES[safeCol]}`;
  }
  if (lang === 'ar') {
    return `${formatNumber(safeRow + 1, lang)}-${ARABIC_COL_NAMES[safeCol]}`;
  }
  if (lang === 'ur') {
    return `${formatNumber(safeRow + 1, lang)}-${URDU_COL_NAMES[safeCol]}`;
  }
  return `${LATIN_COL_NAMES[safeCol]}${safeRow + 1}`;
}

